// Usage: npm run import:csv -- "Order Status - Container.csv"
// Writes data/import.sql (load with `npm run db:seed:local` / `db:seed:remote`)
// and data/import-report.md listing rows that need a manual look.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { parseTrackerCsv } from "./lib/parse-tracker";
import { buildModel, type Model } from "./lib/build-model";

const input = process.argv[2] ?? "Order Status - Container.csv";
const rows = parseTrackerCsv(readFileSync(input, "utf8"));
const model = buildModel(rows);

function sql(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

function inserts<T extends object>(table: string, items: T[]): string[] {
  if (!items.length) return [];
  const cols = Object.keys(items[0]);
  return items.map(
    (it) =>
      `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${cols
        .map((c) => sql((it as Record<string, unknown>)[c]))
        .join(", ")});`,
  );
}

function toSql(m: Model): string {
  const lines = [
    "-- Generated by scripts/import-csv.ts. Re-running replaces all data.",
    "DELETE FROM alerts;",
    "DELETE FROM notes;",
    "DELETE FROM tracking_events;",
    "DELETE FROM containers;",
    "DELETE FROM shipment_pos;",
    "DELETE FROM shipments;",
    "DELETE FROM purchase_orders;",
    "DELETE FROM vendors;",
    ...inserts("vendors", m.vendors),
    ...inserts("purchase_orders", m.pos),
    ...inserts("shipments", m.shipments),
    ...inserts("shipment_pos", m.shipmentPos),
    ...inserts("containers", m.containers),
    ...m.notes.map(
      (n) =>
        `INSERT INTO notes (po_id, shipment_id, author, body, created_at) VALUES (${sql(n.po_id)}, ${sql(
          n.shipment_id,
        )}, 'import', ${sql(n.body)}, ${n.created_at ? sql(n.created_at) : "datetime('now')"});`,
    ),
  ];
  return lines.join("\n") + "\n";
}

mkdirSync("data", { recursive: true });
writeFileSync("data/import.sql", toSql(model));

const active = model.shipments.filter((s) => s.status === "active");
const report = [
  `# Import report`,
  ``,
  `Source: \`${input}\` (${rows.length} non-empty rows)`,
  ``,
  `| Entity | Count |`,
  `|---|---|`,
  `| Vendors | ${model.vendors.length} |`,
  `| Purchase orders | ${model.pos.length} (open: ${model.pos.filter((p) => p.status === "open").length}) |`,
  `| Shipments | ${model.shipments.length} (active: ${active.length}) |`,
  `| Containers | ${model.containers.length} (not yet received: ${model.containers.filter((c) => c.milestone !== "received").length}) |`,
  ``,
  `## Rows to review (${model.issues.length})`,
  ``,
  `| CSV line | PO | Issue |`,
  `|---|---|---|`,
  ...model.issues.map((i) => `| ${i.line} | ${i.po} | ${i.issue.replace(/\|/g, "/")} |`),
  ``,
].join("\n");
writeFileSync("data/import-report.md", report);

console.log(
  `Parsed ${rows.length} rows -> ${model.pos.length} POs, ${model.shipments.length} shipments (${active.length} active), ${model.containers.length} containers, ${model.issues.length} issues.`,
);
console.log("Wrote data/import.sql and data/import-report.md");
